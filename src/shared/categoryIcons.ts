export const maxIconLength = 16

export function categoryIcon(category: Pick<Category, 'name' | 'icon'>): string {
  if (category.icon !== undefined) return category.icon
  return defaultCategoryIcons[category.name.trim().toLowerCase()] ?? ''
}

export function categoryLabel(category: Pick<Category, 'name' | 'icon'>): string {
  const icon = categoryIcon(category)
  return icon === '' ? category.name : `${icon} ${category.name}`
}

const indentUnit = '    '

export function indentedCategoryLabel(
  category: Pick<Category, 'name' | 'icon'>,
  depth: number
): string {
  return `${indentUnit.repeat(depth)}${categoryLabel(category)}`
}
